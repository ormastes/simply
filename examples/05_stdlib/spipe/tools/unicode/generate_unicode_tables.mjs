function parseRange(text) {
  const [a, b = a] = text.trim().split("..").map((v) => Number.parseInt(v, 16));
  return [a, b];
}

function mergeRanges(ranges) {
  const sorted = ranges.toSorted((a, b) => a[0] - b[0] || a[1] - b[1]);
  const out = [];
  for (const [start, end] of sorted) {
    const last = out.at(-1);
    if (last && start <= last[1] + 1) last[1] = Math.max(last[1], end);
    else out.push([start, end]);
  }
  return out;
}

function parseProperty(text, wanted) {
  const ranges = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = strip(raw);
    if (!line) continue;
    const [range, property] = line.split(";").map((v) => v.trim());
    if (property === wanted) ranges.push(parseRange(range));
  }
  return mergeRanges(ranges);
}

function parseUnicodeData(text) {
  const records = [];
  let pending = null;
  for (const raw of text.split(/\r?\n/)) {
    if (!raw) continue;
    const f = raw.split(";");
    const cp = Number.parseInt(f[0], 16);
    if (f[1].endsWith(", First>")) { pending = { cp, f }; continue; }
    if (f[1].endsWith(", Last>")) {
      if (!pending) throw new Error(`range end without start at ${f[0]}`);
      for (let value = pending.cp; value <= cp; value++) records.push({ cp: value, f: pending.f });
      pending = null;
    } else records.push({ cp, f });
  }
  if (pending) throw new Error("unterminated UnicodeData range");
  return records;
}

