function main() {
  const out = args();
  const sourceBytes = Object.fromEntries(SOURCE_NAMES.map((name) => [name, readFileSync(join(out.ucd, name))]));
  const source = Object.fromEntries(Object.entries(sourceBytes).map(([name, bytes]) => [name, bytes.toString("utf8")]));
  const records = parseUnicodeData(source["UnicodeData.txt"]);
  const exclusions = new Set(source["CompositionExclusions.txt"].split(/\r?\n/).map(strip).filter(Boolean).map((v) => Number.parseInt(v, 16)));
  const alphabetic = parseProperty(source["DerivedCoreProperties.txt"], "Alphabetic");
  const softDotted = parseProperty(source["PropList.txt"], "Soft_Dotted");
  const cased = parseProperty(source["DerivedCoreProperties.txt"], "Cased");
  const caseIgnorable = parseProperty(source["DerivedCoreProperties.txt"], "Case_Ignorable");
  const decimal = mergeRanges(records.filter(({ f }) => f[2] === "Nd").map(({ cp }) => [cp, cp]));
  const marks = mergeRanges(records.filter(({ f }) => f[2].startsWith("M")).map(({ cp }) => [cp, cp]));
  const ccc = records.filter(({ f }) => f[3] !== "0").map(({ cp, f }) => [cp, Number(f[3])]);
  const decomposition = [];
  const lowerMap = new Map();
  for (const { cp, f } of records) {
    if (f[5] && !f[5].startsWith("<")) decomposition.push([cp, cps(f[5])]);
    if (f[13]) lowerMap.set(cp, { mapping: [Number.parseInt(f[13], 16)], conditional_mapping: null, condition: null });
  }
  for (const raw of source["SpecialCasing.txt"].split(/\r?\n/)) {
    const line = strip(raw);
    if (!line) continue;
    const f = line.split(";").map((v) => v.trim());
    const conditionTokens = f[4] ? f[4].split(/\s+/) : [];
    if (conditionTokens.some((v) => /^[a-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(v))) continue;
    const cp = Number.parseInt(f[0], 16), condition = conditionTokens.join(" ") || null;
    if (condition) {
      const prior = lowerMap.get(cp) ?? { mapping: [cp], conditional_mapping: null, condition: null };
      lowerMap.set(cp, { ...prior, conditional_mapping: cps(f[1]), condition });
    } else lowerMap.set(cp, { mapping: cps(f[1]), conditional_mapping: null, condition: null });
  }
  const compositions = [];
  for (const [composed, parts] of decomposition) {
    if (parts.length === 2 && !exclusions.has(composed) &&
        (ccc.find(([cp]) => cp === composed)?.[1] ?? 0) === 0 &&
        (ccc.find(([cp]) => cp === parts[0])?.[1] ?? 0) === 0)
      compositions.push([parts[0], parts[1], composed]);
  }
  compositions.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const lowercase = [...lowerMap].map(([cp, value]) => [cp, value.mapping, value.conditional_mapping, value.condition]).sort((a, b) => a[0] - b[0]);
  const tables = {
    ALPHABETIC_RANGES: alphabetic, DECIMAL_NUMBER_RANGES: decimal, MARK_RANGES: marks,
    SOFT_DOTTED_RANGES: softDotted, CASED_RANGES: cased,
    CASE_IGNORABLE_RANGES: caseIgnorable, CANONICAL_COMBINING_CLASS: ccc,
    CANONICAL_DECOMPOSITIONS: decomposition, CANONICAL_COMPOSITIONS: compositions,
    DEFAULT_LOWERCASE: lowercase,
    HANGUL_NFC: { s_base: 0xAC00, l_base: 0x1100, v_base: 0x1161, t_base: 0x11A7, l_count: 19, v_count: 21, t_count: 28 }
  };
  const generatorBytes = readFileSync(fileURLToPath(import.meta.url));
  const meta = { unicode_version: VERSION, generator_version: GENERATOR_VERSION, generator_sha256: sha(generatorBytes) };
  const jsBytes = Buffer.from(renderJs(meta, tables));
  const simpleBytes = Buffer.from(renderSimple(meta, tables));
  mkdirSync(dirname(out.js), { recursive: true });
  mkdirSync(dirname(out.simple), { recursive: true });
  mkdirSync(dirname(out.manifest), { recursive: true });
  writeFileSync(out.js, jsBytes);
  writeFileSync(out.simple, simpleBytes);
  const manifest = {
    schema: "spipe-unicode-table-manifest-v1", unicode_version: VERSION,
    upstream: { repository: "https://github.com/unicode-org/unicodetools", commit: "2c1309ab2ac1de5c62f09089c8ed6bf6f1d37920", path: `unicodetools/data/ucd/${VERSION}` },
    license: { spdx: "Unicode-3.0", file: "examples/05_stdlib/spipe/tools/unicode/UNICODE-LICENSE.txt" },
    generator: { version: GENERATOR_VERSION, file: "examples/05_stdlib/spipe/tools/unicode/generate_unicode_tables.mjs", sha256: sha(generatorBytes), command: "node examples/05_stdlib/spipe/tools/unicode/generate_unicode_tables.mjs" },
    sources: SOURCE_NAMES.map((name) => ({ name, sha256: sha(sourceBytes[name]), bytes: sourceBytes[name].length })),
    generated: [
      { file: "examples/05_stdlib/spipe/src/search/generated/unicode_17_0_0.js", sha256: sha(jsBytes), bytes: jsBytes.length },
      { file: "src/lib/common/search/generated/unicode_17_0_0.spl", sha256: sha(simpleBytes), bytes: simpleBytes.length }
    ],
    contracts: { normalization: "NFC", case_conversion: "Default Lowercase Conversion", case_folding_used: false, token_properties: ["Alphabetic", "Decimal_Number", "Mark", "LOW_LINE"] }
  };
  writeFileSync(out.manifest, `${JSON.stringify(manifest, null, 2)}\n`);
  process.stdout.write(`generated Unicode ${VERSION}: ${tables.CANONICAL_DECOMPOSITIONS.length} decompositions, ${lowercase.length} lowercase mappings\n`);
}

